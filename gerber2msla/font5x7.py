# gerber2msla/font5x7.py
"""The utility's OWN 5 x 7 pixel font — a table of dots, and nothing else.

Why not a TTF: a vector font is rasterised by the platform (FreeType on Linux, another
engine on Windows), and its edges come out grey and slightly different machine to machine.
The plates of one series are compared to each other with a magnifier, so the label must be
the SAME picture everywhere: a table of dots is byte for byte identical by construction.

The glyphs were DRAWN HERE, dot by dot, and no font file was copied: a bitmap table taken
from somewhere would carry its licence into this repository, and the letters of a label are
twenty a year, not a typography problem (decision of 24.10: Latin only, no Cyrillic).

One dot of the table is ``stroke_px`` x ``stroke_px`` SCREEN PIXELS (``patterns.build_text``
does the scaling); a glyph is 5 dots wide and 7 tall, letters stand one blank dot apart, and
a line of text is one line — several lines are several figures.

    "."  a dot that is NOT lit        "#"  a dot that IS lit

The table is data: the cells of `tests/test_text.py` prove that every glyph is its own
picture and that the asymmetric ones (F, L, R, 2, 5, 7, s) differ from their reflections —
a label that reads the same upside down would be useless on a plate that is turned.
"""
